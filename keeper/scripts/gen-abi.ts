// Writes src/abi.ts from the Foundry build output so the keeper (and its Docker image) needs no contracts/out.
//   forge build && pnpm abi
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join(import.meta.dirname, "../../contracts/out");
const abiOf = (name: string) => JSON.parse(readFileSync(join(OUT, `${name}.sol/${name}.json`), "utf8")).abi;

const body =
  `// Generated by scripts/gen-abi.ts from contracts/out. Do not edit by hand; run \`pnpm abi\` after contract changes.\n\n` +
  `export const colonyGameAbi = ${JSON.stringify(abiOf("ColonyGame"), null, 2)} as const;\n\n` +
  `export const seasonPotAbi = ${JSON.stringify(abiOf("SeasonPot"), null, 2)} as const;\n`;
writeFileSync(join(import.meta.dirname, "../src/abi.ts"), body);
console.log("wrote src/abi.ts");
