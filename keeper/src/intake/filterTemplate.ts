import type { LogFilter } from "./types.ts";

/**
 * Renders a Quicknode Streams filter function (plain JavaScript, runs on Quicknode's side).
 * It walks whatever the dataset delivers (e.g. block_with_receipts), keeps only logs matching
 * `filter`, and sends `{ stream, logs }` in standard eth_getLogs shape — or nothing for blocks
 * without a match. The keeper's webhook receiver parses exactly this format.
 */
export function renderFilter(name: string, filter: LogFilter): string {
  const addresses = JSON.stringify(filter.addresses.map((a) => a.toLowerCase()));
  const topics = JSON.stringify(filter.topics.map((t) => (t === null ? null : t.map((x) => x.toLowerCase()))));
  return `// Quicknode Streams filter for "${name}". Generated by keeper/scripts/gen-filters.ts — do not edit by hand.
// Paste into the Stream's filter editor. Dataset: block_with_receipts (or any dataset that contains logs).
var ADDRESSES = ${addresses};
var TOPICS = ${topics};

function toHex(v) {
  if (typeof v === "number") return "0x" + v.toString(16);
  if (typeof v === "string" && /^0x[0-9a-fA-F]*$/.test(v)) return v;
  if (typeof v === "string" && /^[0-9]+$/.test(v)) return "0x" + BigInt(v).toString(16);
  return undefined;
}

function matches(log) {
  if (ADDRESSES.length > 0 && ADDRESSES.indexOf(String(log.address).toLowerCase()) < 0) return false;
  for (var i = 0; i < TOPICS.length; i++) {
    if (TOPICS[i] === null) continue;
    var got = log.topics[i] === undefined ? undefined : String(log.topics[i]).toLowerCase();
    if (got === undefined || TOPICS[i].indexOf(got) < 0) return false;
  }
  return true;
}

function main(stream) {
  var out = [];
  function walk(node, depth, block) {
    if (depth > 8 || node === null || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (var i = 0; i < node.length; i++) walk(node[i], depth + 1, block);
      return;
    }
    if (typeof node.address === "string" && Array.isArray(node.topics) && typeof node.transactionHash === "string") {
      if (node.removed !== true && matches(node)) {
        out.push({
          address: node.address,
          topics: node.topics,
          data: node.data || "0x",
          blockNumber: toHex(node.blockNumber) || block,
          transactionHash: node.transactionHash,
          logIndex: toHex(node.logIndex),
          blockHash: node.blockHash
        });
      }
      return;
    }
    var here = toHex(node.blockNumber) || toHex(node.number) || block;
    for (var k in node) walk(node[k], depth + 1, here);
  }
  walk(stream && stream.data !== undefined ? stream.data : stream, 0, undefined);
  if (out.length === 0) return null;
  return { stream: ${JSON.stringify(name)}, logs: out };
}
`;
}
