// Writes src/lib/abi.ts from the Foundry build (run `forge build` in contracts/ first): node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => JSON.parse(readFileSync(new URL(`../../contracts/out/${name}.sol/${name}.json`, import.meta.url))).abi;
const erc20 = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "o", type: "address" }, { name: "s", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "s", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ name: "", type: "bool" }] },
];
const out = [
  "// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit; regenerate after any contract change.",
  `export const colonyGameAbi = ${JSON.stringify(read("ColonyGame"))} as const;`,
  `export const seasonPotAbi = ${JSON.stringify(read("SeasonPot"))} as const;`,
  `export const erc20Abi = ${JSON.stringify(erc20)} as const;`,
  "",
];
writeFileSync(new URL("../src/lib/abi.ts", import.meta.url), out.join("\n\n"));
